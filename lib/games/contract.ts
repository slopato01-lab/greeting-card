import type { ReactNode } from "react";

/**
 * Контракт игрового модуля — то, что экран открытки передаёт игре
 * и чего от неё ждёт. Первая игра в коде — скретч-карта
 * (components/games/ScratchCard.tsx); пазл и мемори придут по нему же.
 *
 * - `seed` — зерно для всего «случайного», см. lib/games/seed.ts.
 * - `reward` — то, что игра открывает: промокод, фото, текст. Игра
 *   не знает, что внутри, и не решает, как это выглядит.
 * - `photos` — адреса снимков автора, по порядку. Пазл собирает первый,
 *   мемори раскладывает пары из всех. Скретч-карта их не читает.
 *   Может быть пустым — игра обязана это пережить.
 * - `cover` — картинка оформления, если у темы она есть.
 * - `onDone` — вызывается ровно один раз, когда игра пройдена.
 *   Проиграть нельзя (docs/PRODUCT.md): у игры нет ни таймера,
 *   ни состояния поражения.
 *
 * `photos` добавлено 09.10.2026 вместе с пазлом (согласовано
 * с пользователем).
 *
 * Игра сама снимает все слушатели, таймеры и кадры анимации при
 * размонтировании — экран открытки об этом не заботится.
 */
export type GameProps = {
  seed: string;
  reward: ReactNode;
  photos: ReadonlyArray<string>;
  cover: string | null;
  onDone: () => void;
};
